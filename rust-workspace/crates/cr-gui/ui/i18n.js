function normalizeLocaleCode(code) {
  if (!code || typeof code !== "string") return "en-US";
  const clean = code.trim().toLowerCase().replace("_", "-");
  if (clean.startsWith("pt")) return "pt-BR";
  return "en-US";
}

function detectBrowserLocale() {
  const nav = (typeof navigator !== "undefined" && (navigator.language || (navigator.languages && navigator.languages[0]))) || "en-US";
  return normalizeLocaleCode(nav);
}

let activeLocale = detectBrowserLocale();

function resolveLocale(pref, osLocale = "") {
  const normPref = (pref || "system").trim().toLowerCase().replace("_", "-");
  if (normPref === "pt-br" || normPref === "pt") return "pt-BR";
  if (normPref === "en-us" || normPref === "en") return "en-US";
  // "system" -> check OS locale from Rust backend first, then browser navigator
  if (osLocale) return normalizeLocaleCode(osLocale);
  return detectBrowserLocale();
}

function setLocale(code) {
  activeLocale = CHRONO_LOCALES[code] ? code : normalizeLocaleCode(code);
  return activeLocale;
}

function getLocale() {
  return activeLocale;
}

function t(key, params = {}) {
  const dict = CHRONO_LOCALES[activeLocale] || CHRONO_LOCALES["en-US"];
  const fallbackDict = CHRONO_LOCALES["en-US"];
  let str = dict[key] !== undefined ? dict[key] : (fallbackDict[key] !== undefined ? fallbackDict[key] : key);
  if (params && typeof params === "object") {
    for (const [k, v] of Object.entries(params)) {
      str = str.replace(new RegExp(`\\{${k}\\}`, "g"), String(v));
    }
  }
  return str;
}

function applyI18nToDOM() {
  document.documentElement.setAttribute("lang", activeLocale);
  document.title = t("app.title");

  document.querySelectorAll("[data-i18n]").forEach((el) => {
    const key = el.getAttribute("data-i18n");
    if (key) {
      const val = t(key);
      if (typeof val === "string" && val.includes("<") && val.includes(">")) {
        el.innerHTML = val;
      } else {
        el.textContent = val;
      }
    }
  });

  document.querySelectorAll("[data-i18n-html]").forEach((el) => {
    const key = el.getAttribute("data-i18n-html");
    if (key) el.innerHTML = t(key);
  });

  document.querySelectorAll("[data-i18n-placeholder]").forEach((el) => {
    const key = el.getAttribute("data-i18n-placeholder");
    if (key) el.setAttribute("placeholder", t(key));
  });

  document.querySelectorAll("[data-i18n-title]").forEach((el) => {
    const key = el.getAttribute("data-i18n-title");
    if (key) el.setAttribute("title", t(key));
  });
}

window.ChronoI18n = {
  LOCALES: CHRONO_LOCALES,
  resolveLocale,
  setLocale,
  getLocale,
  t,
  applyI18nToDOM,
};
window.t = t;
window.applyI18nToDOM = applyI18nToDOM;
